namespace app\api\v4\controllers;

use app\api\v4\AbstractApi;
use app\api\v4\AcceptableAccepts;
use app\api\v4\AcceptableContentTypes;
use app\api\v4\AcceptableMethods;
use app\api\v4\Controller;
use app\api\v4\Responses\Response;
use app\api\v4\Scope;
use app\exceptions\GC2Exception;
use app\inc\Connection;
use app\inc\Input;
use app\inc\Route2;
use app\models\Configuration as ConfigurationModel;
use OpenApi\Attributes as OA;
use Override;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * v4 management of Vidi configurations, for the database owner.
 *
 * Configurations live in settings.key_value and are shared with the v2
 * Configuration API, so a configuration made here can be opened in the
 * Dashboard and the other way round. Anonymous read of published
 * configurations is served by ConfigurationPublic.
 */
#[OA\Schema(
    schema: "Configuration",
    description: "A Vidi configuration.",
    required: ["name", "published", "description", "body"],
    properties: [
        new OA\Property(property: "key", title: "Key", description: "Server generated identifier.", type: "string", readOnly: true, example: "configuration_my_map_673211a0b1c2d312345678"),
        new OA\Property(property: "name", title: "Name", type: "string", example: "My map"),
        new OA\Property(property: "description", title: "Description", type: "string", example: "Configuration for the public map"),
        new OA\Property(property: "published", title: "Published", description: "When true the configuration can be read without a token.", type: "boolean", example: true),
        new OA\Property(property: "body", title: "Body", description: "The Vidi configuration as JSON text. Must be a JSON object or array. Stored and returned unchanged.", type: "string", example: '{"brandName": "My map"}'),
    ],
    type: "object"
)]
#[AcceptableMethods(['GET', 'POST', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'])]
#[Controller(route: 'api/v4/configurations/[key]', scope: Scope::SUPER_USER_ONLY)]
class Configuration extends AbstractApi
{
    private const string BASE_URI = '/api/v4/configurations/';

    private ConfigurationModel $configuration;

    public function __construct(public readonly Route2 $route, Connection $connection)
    {
        parent::__construct($connection);
        $this->configuration = new ConfigurationModel($connection);
        $this->resource = 'configurations';
    }

    /**
     * @throws GC2Exception
     */
    #[OA\Get(path: '/api/v4/configurations/{key}', operationId: 'getConfiguration', description: "Get one or more configurations (comma separated keys), or list all configurations of the database, published or not.", tags: ['Configuration'],
        parameters: [new OA\Parameter(name: 'key', description: 'Configuration key, or comma separated keys. Omit to list all configurations.', in: 'path', required: false, schema: new OA\Schema(type: 'string'), example: 'configuration_my_map_673211a0b1c2d312345678')],
        responses: [new OA\Response(response: 200, description: 'Ok', content: new OA\JsonContent(oneOf: [new OA\Schema(ref: "#/components/schemas/Configuration"),
            new OA\Schema(type: "array", items: new OA\Items(ref: "#/components/schemas/Configuration"))])), new OA\Response(response: 404, description: 'Not found')])]
    #[AcceptableAccepts(['application/json', '*/*'])]
    #[Override]
    public function get_index(): Response
    {
        $keys = $this->keys();
        if (empty($keys)) {
            return $this->getResponse($this->configuration->list(false));
        }
        $rows = array_map(fn(string $key) => $this->configuration->get($key, false), $keys);
        return $this->getResponse($rows, single: count($rows) === 1);
    }

    /**
     * @throws GC2Exception
     */
    #[OA\Post(path: '/api/v4/configurations', operationId: 'postConfiguration', description: "Create one or more configurations. The key is generated by the server.", tags: ['Configuration'],
        requestBody: new OA\RequestBody(required: true, content: new OA\JsonContent(oneOf: [new OA\Schema(ref: "#/components/schemas/Configuration"),
            new OA\Schema(type: "array", items: new OA\Items(ref: "#/components/schemas/Configuration"))])),
        responses: [new OA\Response(response: 201, description: 'Created'), new OA\Response(response: 400, description: 'Bad request')])]
    #[AcceptableContentTypes(['application/json'])]
    #[AcceptableAccepts(['application/json', '*/*'])]
    #[Override]
    public function post_index(): Response
    {
        $body = json_decode(Input::getBody(), true);
        $items = array_is_list($body) ? $body : [$body];
        $keys = $this->configuration->withTransaction(
            fn() => array_map(fn(array $item) => $this->configuration->create($item), $items)
        );
        return $this->postResponse(self::BASE_URI, $keys);
    }

    /**
     * @throws GC2Exception
     */
    #[OA\Patch(path: '/api/v4/configurations/{key}', operationId: 'patchConfiguration', description: "Update a configuration. Any subset of name, description, published and body. The key never changes.", tags: ['Configuration'],
        parameters: [new OA\Parameter(name: 'key', description: 'Configuration key.', in: 'path', required: true, schema: new OA\Schema(type: 'string'), example: 'configuration_my_map_673211a0b1c2d312345678')],
        requestBody: new OA\RequestBody(required: true, content: new OA\JsonContent(ref: "#/components/schemas/Configuration")),
        responses: [new OA\Response(response: 303, description: 'Updated'), new OA\Response(response: 400, description: 'Bad request'), new OA\Response(response: 404, description: 'Not found')])]
    #[AcceptableContentTypes(['application/json'])]
    #[AcceptableAccepts(['application/json', '*/*'])]
    #[Override]
    public function patch_index(): Response
    {
        $key = $this->keys()[0];
        $body = json_decode(Input::getBody(), true);
        $this->configuration->withTransaction(fn() => $this->configuration->patch($key, $body));
        return $this->patchResponse(self::BASE_URI, [$key]);
    }

    /**
     * @throws GC2Exception
     */
    #[OA\Delete(path: '/api/v4/configurations/{key}', operationId: 'deleteConfiguration', description: "Delete one or more configurations (comma separated keys). If any key is missing nothing is deleted.", tags: ['Configuration'],
        parameters: [new OA\Parameter(name: 'key', description: 'Configuration key, or comma separated keys.', in: 'path', required: true, schema: new OA\Schema(type: 'string'), example: 'configuration_my_map_673211a0b1c2d312345678')],
        responses: [new OA\Response(response: 204, description: 'Deleted'), new OA\Response(response: 404, description: 'Not found')])]
    #[Override]
    public function delete_index(): Response
    {
        $keys = $this->keys();
        $this->configuration->withTransaction(fn() => $this->configuration->remove($keys));
        return $this->deleteResponse();
    }

    #[Override]
    public function put_index(): Response
    {
        throw new GC2Exception("Method not allowed", 405, null, "METHOD_NOT_ALLOWED");
    }

    /**
     * @throws GC2Exception
     */
    #[Override]
    public function validate(): void
    {
        $method = Input::getMethod();
        $keys = $this->keys();

        if ($method == 'post' && !empty($keys)) {
            throw new GC2Exception("POST does not take a key; it is generated by the server.", 400, null, "INVALID_REQUEST");
        }
        if (in_array($method, ['patch', 'delete']) && empty($keys)) {
            throw new GC2Exception("A key is required.", 400, null, "INVALID_REQUEST");
        }
        if ($method == 'patch' && count($keys) > 1) {
            throw new GC2Exception("PATCH takes a single key.", 400, null, "INVALID_REQUEST");
        }
        foreach ($keys as $key) {
            ConfigurationModel::assertKey($key);
        }
        if (in_array($method, ['post', 'patch'])) {
            self::assertBodyShape(json_decode(Input::getBody(), true), $method);
        }
        $this->validateRequest(self::getAssert(), Input::getBody(), $method);
    }

    /**
     * POST takes one object or a non-empty list of objects; PATCH takes one
     * non-empty object. Checked here because the field validation below
     * accepts null and does not expect scalars.
     *
     * @throws GC2Exception
     */
    private static function assertBodyShape(mixed $body, string $method): void
    {
        $isObject = fn(mixed $v): bool => is_array($v) && !empty($v) && !array_is_list($v);
        $ok = $isObject($body);
        if (!$ok && $method == 'post' && is_array($body) && !empty($body)) {
            $ok = array_all($body, $isObject);
        }
        if (!$ok) {
            $expected = $method == 'post' ? "a configuration object or a list of them" : "an object with the fields to change";
            throw new GC2Exception("The request body must be $expected.", 400, null, "INVALID_REQUEST");
        }
    }

    static public function getAssert(): Assert\Collection
    {
        // Type alone lets null through, and the Dashboard cannot save a configuration holding nulls
        $constraints = [
            'name' => [new Assert\Type('string'), new Assert\NotBlank()],
            'description' => [new Assert\NotNull(), new Assert\Type('string')],
            'published' => [new Assert\NotNull(), new Assert\Type('bool')],
            'body' => [new Assert\NotNull(), new Assert\Type('string')],
        ];
        $wrap = Input::getMethod() == 'patch' ? Assert\Optional::class : Assert\Required::class;
        return new Assert\Collection(array_map(fn(array $c) => new $wrap($c), $constraints));
    }

    /**
     * The key segment split on commas; empty when the route has no key.
     *
     * @return array<string>
     */
    private function keys(): array
    {
        // Not getParam(): it urldecodes, which turns the '+' of a Dashboard-made key into a space
        $raw = rawurldecode($this->route->params['key'] ?? '');
        return $raw === '' ? [] : explode(',', $raw);
    }
}
